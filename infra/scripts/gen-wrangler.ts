// Usage: bun run infra/scripts/gen-wrangler.ts
// Derives the per-worker wrangler configs in infra/wrangler/ from
// infra/workers.manifest.ts (the single IaC source of truth). Output is
// GITIGNORED. Edit the manifest, never this output. Ported from
// gumpbox-landing (infra/scripts/gen-wrangler.ts), 2026-11-25.
import { mkdirSync, writeFileSync } from 'node:fs';
import { RESOURCE_PREFIX, resources, workers, type WorkerEntry } from '../workers.manifest.ts';

/** Paths in the generated config are relative to infra/wrangler/. */
const fromConfig = (appDir: string, p: string): string => `../../${appDir === '.' ? '' : `${appDir}/`}${p}`;

/** Production workers get no debug origins (workers.dev / preview URLs) once
 * they own routes. Bootstrap state: with no routes yet, workers.dev is the
 * only host, so it stays on until cutover. */
const debugOrigins = (w: WorkerEntry): { workers_dev: boolean; preview_urls: boolean } => {
  const on = w.env === 'staging' || w.routes.length === 0;
  return { workers_dev: on, preview_urls: on };
};

/** Every resource name must carry the yggdrasight- prefix (owner rule). The
 * template-literal types enforce it at compile time; this enforces it at
 * generate time too, since bun does not type-check. */
function assertPrefixed(label: string, name: string): void {
  if (!name.startsWith(RESOURCE_PREFIX)) throw new Error(`${label} "${name}" must start with "${RESOURCE_PREFIX}" (workers.manifest.ts naming rule)`);
}

export function wranglerConfig(w: WorkerEntry): Record<string, unknown> {
  assertPrefixed('worker', w.name);
  const cfg: Record<string, unknown> = {
    $schema: fromConfig('.', 'node_modules/wrangler/config-schema.json'),
    name: w.name,
    main: fromConfig(w.appDir, '.open-next/worker.js'),
    compatibility_date: w.compatibilityDate,
    compatibility_flags: [...w.compatibilityFlags],
    assets: { binding: 'ASSETS', directory: fromConfig(w.appDir, '.open-next/assets') },
    vars: w.vars,
  };
  if (w.kv?.length) {
    cfg.kv_namespaces = w.kv.map((k) => ({ binding: k.binding, ...(resources.kv[k.ref].id ? { id: resources.kv[k.ref].id } : {}) }));
  }
  if (w.d1?.length) {
    cfg.d1_databases = w.d1.map((d) => {
      const r = resources.d1[d.ref];
      assertPrefixed('D1 database', r.databaseName);
      return { binding: d.binding, database_name: r.databaseName, ...(r.databaseId ? { database_id: r.databaseId } : {}) };
    });
  }
  if (w.r2?.length) {
    cfg.r2_buckets = w.r2.map((b) => {
      const r = resources.r2[b.ref];
      assertPrefixed('R2 bucket', r.bucketName);
      return { binding: b.binding, bucket_name: r.bucketName };
    });
  }
  Object.assign(cfg, debugOrigins(w));
  cfg.routes = w.routes.map((r) => ({ pattern: r.pattern, custom_domain: r.customDomain }));
  cfg.observability = { enabled: true };
  return cfg;
}

const HEADER = `// Generated by infra/scripts/gen-wrangler.ts from infra/workers.manifest.ts.
// Gitignored artifact: edit the manifest, then \`bun run iac:gen\`.
`;

if (import.meta.main) {
  const outDir = new URL('../wrangler/', import.meta.url).pathname;
  mkdirSync(outDir, { recursive: true });
  for (const [key, w] of Object.entries(workers)) {
    const file = `${outDir}${key}.jsonc`;
    writeFileSync(file, `${HEADER}${JSON.stringify(wranglerConfig(w), null, 2)}\n`);
    console.log(`wrote ${file}`);
  }
}
